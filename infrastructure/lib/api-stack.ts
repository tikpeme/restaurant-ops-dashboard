import * as cdk from "aws-cdk-lib";
import * as apigateway from "aws-cdk-lib/aws-apigateway";
import { AuthStack } from "./auth-stack";
import { DatabaseStack } from "./database-stack";
import { ArchiveStack } from "./archive-stack";
import { Construct } from "constructs";
import * as lambda from "aws-cdk-lib/aws-lambda";
import * as lambdaNodejs from "aws-cdk-lib/aws-lambda-nodejs";
import * as path from "path";

export interface ApiStackProps extends cdk.StackProps {
  authStack: AuthStack;
  databaseStack: DatabaseStack;
  archiveStack: ArchiveStack;
}

export class ApiStack extends cdk.Stack {
  public readonly api: apigateway.RestApi;

  constructor(scope: Construct, id: string, props?: ApiStackProps) {
    super(scope, id, props);

    const { authStack, databaseStack, archiveStack } = props!;

    // NodejsFunction bundles TypeScript with esbuild, so there is no manual compile step
    const apiLambda = new lambdaNodejs.NodejsFunction(this, "ApiLambda", {
      runtime: lambda.Runtime.NODEJS_24_X,
      // Just the exported function name; CDK knows the file from `entry`
      handler: "handler",
      // Absolute path to the TypeScript entry file
      entry: path.join(__dirname, "../../backend/index.ts"),
      // projectRoot must contain the entry file, so it points at backend/
      projectRoot: path.join(__dirname, "../../backend"),
      // Required because projectRoot is outside the CDK project
      depsLockFilePath: path.join(__dirname, "../../backend/package-lock.json"),
      bundling: {
        // AWS SDK v3 ships with the Lambda runtime, so it isn't bundled
        externalModules: [
          "@aws-sdk/client-dynamodb",
          "@aws-sdk/lib-dynamodb",
          "@aws-sdk/client-eventbridge",
        ],
      },
      environment: {
        TABLE_NAME: databaseStack.reportsTable.tableName,
        ARCHIVE_BUCKET_NAME: archiveStack.archiveBucket.bucketName,
        // Default EventBridge bus; a custom bus is recommended in production
        EVENT_BUS_NAME: "default",
      },
    });

    // Least privilege: the Lambda only gets what it needs on each resource
    databaseStack.reportsTable.grantReadWriteData(apiLambda);
    archiveStack.archiveBucket.grantWrite(apiLambda);

    // Needed to publish low revenue alerts to EventBridge
    apiLambda.addToRolePolicy(
      new cdk.aws_iam.PolicyStatement({
        actions: ["events:PutEvents"],
        resources: ["*"],
      }),
    );

    // Every route requires a valid Cognito JWT, verified before the Lambda runs
    const authorizer = new apigateway.CognitoUserPoolsAuthorizer(
      this,
      "CognitoAuthorizer",
      {
        cognitoUserPools: [authStack.userPool],
      },
    );

    this.api = new apigateway.RestApi(this, "RestaurantOpsApi", {
      restApiName: "Restaurant Operations API",
      description: "This API serves the restaurant operations dashboard.",
      deployOptions: {
        stageName: "v1",
      },
      defaultCorsPreflightOptions: {
        allowOrigins: apigateway.Cors.ALL_ORIGINS,
        allowMethods: apigateway.Cors.ALL_METHODS,
        allowHeaders: [
          "Content-Type",
          "Authorization",
          "X-Amz-Date",
          "X-Api-Key",
        ],
      },
    });

    // Responses generated by API Gateway itself (expired token, authorizer
    // rejection) never pass through the Lambda, so they need CORS headers here.
    // Without this, the browser reports a 401 as a CORS error.
    // The inner single quotes are required: API Gateway evaluates these as expressions.
    this.api.addGatewayResponse("Default4xx", {
      type: apigateway.ResponseType.DEFAULT_4XX,
      responseHeaders: {
        "Access-Control-Allow-Origin": "'*'",
        "Access-Control-Allow-Headers": "'Content-Type,Authorization'",
      },
    });
    this.api.addGatewayResponse("Default5xx", {
      type: apigateway.ResponseType.DEFAULT_5XX,
      responseHeaders: {
        "Access-Control-Allow-Origin": "'*'",
        "Access-Control-Allow-Headers": "'Content-Type,Authorization'",
      },
    });

    // All routes are protected by the Cognito authorizer.
    // Which group can call which route is enforced inside the Lambda.
    const reportsResource = this.api.root.addResource("reports");

    // POST /reports: manager (or owner) submits an end-of-night report
    reportsResource.addMethod(
      "POST",
      new apigateway.LambdaIntegration(apiLambda),
      { authorizationType: apigateway.AuthorizationType.COGNITO, authorizer },
    );

    // GET /reports: owner/investor dashboard, all locations for a date via the GSI
    reportsResource.addMethod(
      "GET",
      new apigateway.LambdaIntegration(apiLambda),
      { authorizationType: apigateway.AuthorizationType.COGNITO, authorizer },
    );

    const locationResource = reportsResource.addResource("{locationId}");

    // GET /reports/{locationId}: one location's history by partition key
    locationResource.addMethod(
      "GET",
      new apigateway.LambdaIntegration(apiLambda),
      { authorizationType: apigateway.AuthorizationType.COGNITO, authorizer },
    );

    const reportDateResource = locationResource.addResource("{reportDate}");

    // PUT /reports/{locationId}/{reportDate}: edit within the 24hr window.
    // The window is enforced by a ConditionExpression on the update in Lambda.
    reportDateResource.addMethod(
      "PUT",
      new apigateway.LambdaIntegration(apiLambda),
      { authorizationType: apigateway.AuthorizationType.COGNITO, authorizer },
    );

    new cdk.CfnOutput(this, "ApiUrl", {
      value: this.api.url,
      exportName: "RestaurantOpsApiUrl",
    });
  }
}
